'use strict';
// Generates the Flutter data files from data/*.json so there is one source of truth.
//   node scripts/generate.js [path/to/grow_buddy_client]
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const app = path.resolve(process.argv[2] || path.join(root, '..', 'grow_buddy_client'));
const plants = require('../data/plants.json');
const data = require('../data/symptoms.json');

const q = (s) =>
  "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\r?\n/g, '\\n') + "'";
const list = (arr, indent) => '[\n' + arr.map((s) => `${indent}  ${q(s)},`).join('\n') + `\n${indent}]`;

const HEADER = '// GENERATED by grow_buddy_server/scripts/generate.js from data/*.json. Do not edit by hand.\n';

function plantsDart() {
  const items = plants
    .map(
      (p) => `  PlantGuide(
    id: ${q(p.id)},
    name: ${q(p.name)},
    emoji: ${q(p.emoji)},
    difficulty: ${q(p.difficulty)},
    minAfternoonHrs: ${p.minAfternoonHrs},
    maxAfternoonHrs: ${p.maxAfternoonHrs},
    heatSensitive: ${p.heatSensitive},
    waterEveryDays: ${p.waterEveryDays},
    daysToSellMin: ${p.daysToSellMin},
    daysToSellMax: ${p.daysToSellMax},
    water: ${q(p.water)},
    soil: ${q(p.soil)},
    timeToSell: ${q(p.timeToSell)},
    sellNote: ${q(p.sellNote)},
    steps: ${list(p.steps, '    ')},
    afternoonTips: ${list(p.afternoonTips, '    ')},
  ),`
    )
    .join('\n');
  return `${HEADER}import '../models.dart';

const List<PlantGuide> plantGuides = [
${items}
];

PlantGuide? guideById(String id) {
  for (final g in plantGuides) {
    if (g.id == id) return g;
  }
  return null;
}
`;
}

function symptomsDart() {
  const causeDefs = Object.entries(data.causes)
    .map(
      ([id, c]) => `const Cause _${id} = Cause(
  ${q(id)},
  ${q(c.title)},
  ${q(c.why)},
  ${q(c.fix)},
);`
    )
    .join('\n');
  const causeMap = Object.keys(data.causes)
    .map((id) => `  ${q(id)}: _${id},`)
    .join('\n');
  const symptomDefs = data.symptoms
    .map((s) => `  Symptom(${q(s.id)}, ${q(s.label)}, [${s.causes.map((c) => '_' + c).join(', ')}]),`)
    .join('\n');
  return `${HEADER}class Cause {
  final String id;
  final String title;
  final String why;
  final String fix;
  const Cause(this.id, this.title, this.why, this.fix);
}

class Symptom {
  final String id;
  final String label;
  final List<Cause> causes;
  const Symptom(this.id, this.label, this.causes);
}

${causeDefs}

const Map<String, Cause> causesById = {
${causeMap}
};

const List<Symptom> symptoms = [
${symptomDefs}
];

class RankedCause {
  final Cause cause;
  final double score;
  RankedCause(this.cause, this.score);
}

/// Rank causes by how many selected symptoms point at them.
/// Each symptom hands out a total weight of 1, split by position (earlier causes
/// weigh more), so a symptom with a single possible cause counts for more.
List<RankedCause> rankCauses(Set<String> selected) {
  final scores = <String, double>{};
  for (final s in symptoms) {
    if (!selected.contains(s.id)) continue;
    final n = s.causes.length;
    final total = n * (n + 1) / 2;
    for (var i = 0; i < n; i++) {
      final id = s.causes[i].id;
      scores[id] = (scores[id] ?? 0) + (n - i) / total;
    }
  }
  final list = scores.entries
      .map((e) => RankedCause(causesById[e.key]!, e.value))
      .toList();
  list.sort((a, b) {
    final d = b.score - a.score;
    if (d.abs() > 1e-9) return d > 0 ? 1 : -1;
    return a.cause.id.compareTo(b.cause.id);
  });
  return list;
}
`;
}

const outDir = path.join(app, 'lib', 'data');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'plant_guides.dart'), plantsDart());
fs.writeFileSync(path.join(outDir, 'symptoms.dart'), symptomsDart());
console.log(`wrote ${plants.length} plants and ${data.symptoms.length} symptoms to ${outDir}`);
